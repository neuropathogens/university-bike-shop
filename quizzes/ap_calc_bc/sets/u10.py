# FRQ: f(x) = sum (-1)^(n+1) (x-1)^n / (n 2^n) = ln(1 + (x-1)/2)
fx = sp.log(1 + (x - 1) / 2)
ser = sp.series(fx, x, 1, 4).removeO()
assert sp.expand(ser - ((x - 1) / 2 - (x - 1) ** 2 / 8 + (x - 1) ** 3 / 24)) == 0
assert sp.Rational(1, 2) - sp.Rational(1, 8) == sp.Rational(3, 8) and sp.Rational(1, 24) < sp.Rational(1, 20)
assert abs(math.log(1.5) - 0.375) < 1 / 24

